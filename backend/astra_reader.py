class AstraReader:
    """
    Read and extract data from Wyatt ASTRA `.afe8` files.

    Parameters
    ----------
    file_path : str or Path
        Path to the `.afe8` file.

    Examples
    --------
    >>> reader = AstraReader("sample.afe8")
    >>> print(reader.experiment)
    >>> mals_data = reader.get_mals_chromatogram()
    >>> ri_data = reader.get_ri_chromatogram()
    >>> results = reader.get_results()
    """

    def __init__(self, file_path: Union[str, Path]):
        self.file_path = Path(file_path)
        self._conn: Optional[sqlite3.Connection] = None
        self._load()

    def _load(self) -> None:
        """Decompress the gzip file and open the SQLite database."""
        import tempfile

        with gzip.open(self.file_path, "rb") as f:
            db_bytes = f.read()

        # Write decompressed SQLite database to a temp file
        self._temp_file = tempfile.NamedTemporaryFile(
            suffix=".sqlite", delete=False, prefix="astra_"
        )
        self._temp_file.write(db_bytes)
        self._temp_file.close()

        uri_path = self._temp_file.name.replace("\\", "/")
        self._conn = sqlite3.connect(f"file:{uri_path}?mode=ro", uri=True)
        self._conn.execute("PRAGMA query_only=ON;")
        self._conn.row_factory = None  # Default — tuples
        self._mals_table: Optional[str] = None

    def __del__(self):
        self.close()
        # Clean up temp file
        if hasattr(self, "_temp_file") and hasattr(self._temp_file, "name"):
            try:
                import os
                os.unlink(self._temp_file.name)
            except OSError:
                pass

    def close(self) -> None:
        """Close the database connection."""
        if self._conn is not None:
            self._conn.close()
            self._conn = None

    def _query(self, sql: str, params: tuple = ()) -> list:
        """Execute a SQL query and return all rows."""
        cur = self._conn.cursor()
        cur.execute(sql, params)
        rows = cur.fetchall()
        cur.close()
        return rows

    def _query_one(self, sql: str, params: tuple = ()) -> Optional[tuple]:
        """Execute a SQL query and return the first row."""
        cur = self._conn.cursor()
        cur.execute(sql, params)
        row = cur.fetchone()
        cur.close()
        return row

    @staticmethod
    def _guid_str(blob_or_str) -> str:
        """Convert a GUID (stored as string or BLOB) to a clean string."""
        if isinstance(blob_or_str, str):
            return blob_or_str
        if isinstance(blob_or_str, (bytes, bytearray)):
            return blob_or_str.decode("utf-8", errors="replace")
        return str(blob_or_str)

    def _resolve_mals_table(self) -> Optional[str]:
        """Return the name of the first present MALS profile table, cached."""
        if self._mals_table is not None:
            return self._mals_table if self._mals_table != "" else None
        tables = set(self.list_tables())
        for candidate in MALS_PROFILE_TABLES:
            if candidate in tables:
                self._mals_table = candidate
                return candidate
        self._mals_table = ""
        return None

