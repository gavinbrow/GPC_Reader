def _main():
    import json
    import sys

    if len(sys.argv) < 2:
        print("Usage: python astra_reader.py <file.afe8> [--summary] [--tables] [--results]")
        sys.exit(1)

    file_path = sys.argv[1]
    reader = AstraReader(file_path)

    if "--tables" in sys.argv:
        print("\n=== Populated Tables ===")
        for name, count in reader.list_populated_tables().items():
            print(f"  {name}: {count} rows")

    if "--summary" in sys.argv or "--tables" not in sys.argv:
        print("\n=== Experiment Summary ===")
        summary = reader.get_summary()
        print(json.dumps(summary, indent=2, default=str))

    if "--results" in sys.argv:
        print("\n=== All Results ===")
        for r in reader.results:
            print(f"  Peak {r.peak} | {r.instrument_name:25s} | {r.data_name:40s} | {r.value:.6g}")

    reader.close()


if __name__ == "__main__":
    _main()
