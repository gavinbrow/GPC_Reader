    @property
    def uv(self) -> UVInfo:
        """Return UV detector info."""
        row = self._query_one("SELECT * FROM WHplcUVDeviceProfile LIMIT 1")
        if row is None:
            # Try generic UV
            row = self._query_one("SELECT * FROM WGenericUVInstrumentProfile LIMIT 1")
            if row is None:
                return UVInfo()
            cols = [d[0] for d in self._conn.execute("SELECT * FROM WGenericUVInstrumentProfile LIMIT 1").description]
        else:
            cols = [d[0] for d in self._conn.execute("SELECT * FROM WHplcUVDeviceProfile LIMIT 1").description]
        d = dict(zip(cols, row, strict=False))

        # Decode wavelengths blob (present on WGenericUVInstrumentProfile)
        wavelengths = []
        wl_blob = d.get("m_vWavelengths")
        if wl_blob and isinstance(wl_blob, (bytes, bytearray)):
            wl_data = decode_raw_blob_doubles(wl_blob)
            wavelengths = wl_data.tolist()

        # WHplcUVDeviceProfile does not store the wavelengths in a blob; it only
        # records the channel counts/indices.  The actual monitored wavelengths
        # live on the injected-sample profile (primary/secondary UV wavelength).
        # Fall back to those so the UI shows real nm values instead of channel
        # numbers (which previously surfaced as "1 nm" / "2 nm").
        if not wavelengths:
            num_channels = (
                d.get("numberUVChannels")
                or d.get("m_nNumberUVChannels")
                or 0
            )
            primary = d.get("primaryUVWavelength")
            secondary = d.get("secondaryUVWavelength")
            if primary is None or secondary is None:
                samp = self.sample
                if primary is None:
                    primary = samp.primary_uv_wavelength
                if secondary is None:
                    secondary = samp.secondary_uv_wavelength
            candidates = [w for w in (primary, secondary) if w]
            if candidates:
                if num_channels and num_channels <= len(candidates):
                    wavelengths = candidates[:num_channels]
                else:
                    wavelengths = candidates

        cell_length = (
            d.get("m_dCellLength")
            or d.get("cellLength")
            or 10.0
        )
        active_channel = (
            d.get("m_activeChannel")
            or d.get("activeChannel")
            or 0
        )

        return UVInfo(
            name=d.get("m_sName", "") or "",
            description=d.get("m_sDescription", "") or "",
            cell_length=cell_length,
            active_channel=active_channel,
            wavelengths=wavelengths,
        )

