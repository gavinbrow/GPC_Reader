    @property
    def mals(self) -> MALSInfo:
        """Return MALS (DAWN) detector info."""
        table = self._resolve_mals_table()
        if table is None:
            return MALSInfo()
        row = self._query_one(f'SELECT * FROM "{table}" LIMIT 1')
        if row is None:
            return MALSInfo()
        cols = [d[0] for d in self._conn.execute(f'SELECT * FROM "{table}" LIMIT 1').description]
        d = dict(zip(cols, row, strict=False))
        angles = decode_raw_blob_doubles(d.get("m_vDetectorAngles", b""))
        norm_coeffs = decode_raw_blob_doubles(d.get("m_vNormalizationCoefficients", b""))
        num_detectors = d.get("m_nNumberOfDetectors", 8) or 8
        # The angles blob can carry a trailing spurious value beyond the actual
        # detector count (e.g. 9 doubles for an 8-detector DAWN). Trim to the
        # reported detector count so the metadata matches the signal columns.
        if num_detectors and len(angles) > num_detectors:
            angles = angles[:num_detectors]
        return MALSInfo(
            name=d.get("m_sName", "") or "",
            description=d.get("m_sDescription", "") or "",
            temperature=d.get("m_dTemperature", 25.0) or 25.0,
            wavelength=d.get("m_dWavelength", 658.0) or 658.0,
            num_detectors=num_detectors,
            calibration_constant=d.get("m_dCalibrationConstant", 1.0) or 1.0,
            detector_angles=angles,
            normalization_coefficients=norm_coeffs,
            instrumental_term=d.get("m_dInstrumentalTerm", 1.0) or 1.0,
            mixing_term=d.get("m_dMixingTerm", 50.0) or 50.0,
            firmware_version=d.get("firmwareVersion", "") or "",
        )

