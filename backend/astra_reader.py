    @property
    def vector_data(self) -> list[VectorData]:
        """Return all vector (1-D time-series) data series."""
        rows = self._query("""
            SELECT m_nDataName, m_nValueName, m_nValueUnits, m_nIndexName, m_nIndexUnits,
                   m_nPeak, m_sInstrumentClassName, dataCategory, m_bTrueDouble,
                   m_vIndex, m_vValue
            FROM WVectorData
            ORDER BY m_sInstrumentClassName, m_nDataName
        """)
        result = []
        for row in rows:
            (dname_code, vname_code, vunits_code, iname_code, iunits_code,
             peak, inst_class, dcat, true_dbl, v_idx, v_val) = row

            # Determine if data is doubles or floats
            is_double = true_dbl == 1

            # Decode index (always doubles)
            idx_vals = decode_blob(v_idx, is_double=True)

            # Decode values
            val_vals = decode_blob(v_val, is_double=is_double)

            result.append(VectorData(
                data_name_code=dname_code or 0,
                data_name=lookup_data_name(dname_code or 0),
                value_name_code=vname_code or 0,
                value_name=lookup_data_name(vname_code or 0),
                value_units_code=vunits_code or 0,
                index_name_code=iname_code or 0,
                index_name=lookup_data_name(iname_code or 0),
                index_units_code=iunits_code or 0,
                index_units=lookup_data_name(iunits_code or 0),
                peak=peak or 0,
                instrument_class=inst_class or "",
                instrument_name=lookup_instrument(inst_class or ""),
                data_category=dcat or 0,
                is_true_double=bool(true_dbl),
                index_values=idx_vals,
                data_values=val_vals,
            ))
        return result

    @property
    def matrix_data(self) -> list[MatrixData]:
        """Return all matrix (2-D) data series."""
        rows = self._query("""
            SELECT m_nDataName, m_nValueName, m_nIndexName, m_nIndexUnits,
                   m_nColumnIndexName, m_nPeak, m_sInstrumentClassName,
                   dataCategory, m_bTrueDouble, m_vIndex, m_vColumnIndex, m_vvValue
            FROM WMatrixData
            ORDER BY m_sInstrumentClassName, m_nDataName
        """)
        result = []
        for row in rows:
            (dname_code, vname_code, iname_code, iunits_code,
             ciname_code, peak, inst_class, dcat, true_dbl,
             v_idx, v_cidx, v_val) = row

            is_double = true_dbl == 1

            # Row index (time axis) - always doubles
            row_idx = decode_blob(v_idx, is_double=True)

            # Column index (detector/channel numbers) - raw doubles (no zlib)
            col_idx = decode_raw_blob_doubles(v_cidx)

            # Values matrix
            val_1d = decode_blob(v_val, is_double=is_double)
            n_cols = len(col_idx) if len(col_idx) > 0 else 0
            n_rows = len(row_idx) if len(row_idx) > 0 else 0
            if n_cols > 0 and n_rows > 0 and len(val_1d) == n_rows * n_cols:
                values = val_1d.reshape(n_rows, n_cols)
            elif n_cols > 0 and len(val_1d) % n_cols == 0:
                values = val_1d.reshape(-1, n_cols)
            else:
                values = val_1d  # Flat array as fallback

            result.append(MatrixData(
                data_name_code=dname_code or 0,
                data_name=lookup_data_name(dname_code or 0),
                value_name_code=vname_code or 0,
                value_name=lookup_data_name(vname_code or 0),
                index_name_code=iname_code or 0,
                index_name=lookup_data_name(iname_code or 0),
                index_units_code=iunits_code or 0,
                index_units=lookup_data_name(iunits_code or 0),
                column_index_name_code=ciname_code or 0,
                column_index_name=lookup_data_name(ciname_code or 0),
                peak=peak or 0,
                instrument_class=inst_class or "",
                instrument_name=lookup_instrument(inst_class or ""),
                data_category=dcat or 0,
                is_true_double=bool(true_dbl),
                row_index=row_idx,
                column_index=col_idx,
                values=values,
            ))
        return result

