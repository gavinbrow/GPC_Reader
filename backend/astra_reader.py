    # ── Low-level table access ───────────────────────────────────────────

    def list_tables(self) -> list[str]:
        """Return a list of all table names in the database."""
        rows = self._query("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")
        return [r[0] for r in rows]

    def list_populated_tables(self) -> dict[str, int]:
        """Return a dictionary of {table_name: row_count} for all non-empty tables."""
        result = {}
        for table_name in self.list_tables():
            count = self._query_one(f'SELECT COUNT(*) FROM "{table_name}"')[0]
            if count > 0:
                result[table_name] = count
        return result

    def raw_query(self, sql: str) -> list[tuple]:
        """
        Execute a raw SQL query against the SQLite database.

        Only SELECT statements are permitted; any other statement raises
        ValueError. The connection is also opened read-only and has
        ``PRAGMA query_only=ON`` set, so this guard is defense-in-depth.

        Parameters
        ----------
        sql : str
            SQL query string. Must start with SELECT (case-insensitive).

        Returns
        -------
        list of tuples
            Query results.
        """
        if not sql.lstrip().upper().startswith("SELECT"):
            raise ValueError("raw_query only permits SELECT statements")
        return self._query(sql)

    def get_table_as_dicts(self, table_name: str, limit: Optional[int] = None) -> list[dict]:
        """
        Return all rows from a table as a list of dictionaries.

        Parameters
        ----------
        table_name : str
            Name of the table. Must be present in ``list_tables()``.
        limit : int, optional
            Maximum number of rows to return.

        Returns
        -------
        list of dict
            Each dict maps column name -> value.
        """
        if table_name not in self.list_tables():
            raise ValueError(f"Unknown table: {table_name}")
        sql = f'SELECT * FROM "{table_name}"'
        cur = self._conn.cursor()
        if limit is not None:
            cur.execute(sql + " LIMIT ?", (limit,))
        else:
            cur.execute(sql)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        cur.close()
        return [dict(zip(cols, row, strict=False)) for row in rows]


