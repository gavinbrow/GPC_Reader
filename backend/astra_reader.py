def decode_blob(blob: bytes, is_double: bool = True) -> np.ndarray:
    """
    Decode an ASTRA data BLOB.

    BLOB format:
        - 16-byte header: 4 × uint32 (blob_size, uncompressed_size, count, element_size)
        - Remaining bytes: zlib-compressed data (magic 0x78 0x9c) OR raw data

    Parameters
    ----------
    blob : bytes
        The raw BLOB from the SQLite database.
    is_double : bool
        If True, interpret data as 8-byte doubles (float64).
        If False, interpret data as 4-byte floats (float32).

    Returns
    -------
    np.ndarray
        Array of decoded values.
    """
    if blob is None or len(blob) == 0:
        return np.array([])

    # Read 16-byte header
    if len(blob) >= 16:
        blob_size, uncomp_size, count, elem_size = struct.unpack_from("<4I", blob, 0)
        payload = blob[16:]
    else:
        payload = blob

    # Check for zlib compression (magic bytes 0x78 0x9c)
    if len(payload) >= 2 and payload[0] == 0x78 and payload[1] in (0x01, 0x9C, 0xDA):
        try:
            data = zlib.decompress(payload)
        except zlib.error:
            # Maybe the entire blob (including header) is compressed
            try:
                data = zlib.decompress(blob)
            except zlib.error:
                # Fall back to raw payload
                data = payload
    else:
        # Raw data (not compressed)
        data = payload

    # Interpret as doubles or floats
    if is_double:
        n = len(data) // 8
        if n == 0:
            return np.array([])
        return np.frombuffer(data[: n * 8], dtype="<f8").copy()
    else:
        n = len(data) // 4
        if n == 0:
            return np.array([])
        return np.frombuffer(data[: n * 4], dtype="<f4").copy()


def decode_raw_blob_doubles(blob: bytes) -> np.ndarray:
    """
    Decode a raw (non-compressed) BLOB that has a 16-byte header followed by doubles.
    Used for small blobs like detector angles and normalization coefficients.
    """
    if blob is None or len(blob) <= 16:
        return np.array([])
    data = blob[16:]
    n = len(data) // 8
    if n == 0:
        return np.array([])
    return np.frombuffer(data[: n * 8], dtype="<f8").copy()


def encode_blob(values: np.ndarray, is_double: bool = True) -> bytes:
    """
    Encode a NumPy array into an ASTRA-compatible BLOB.

    This is the inverse of :func:`decode_blob`.  The BLOB format is a 16-byte
    header (4 x uint32: blob_size, uncompressed_size, count, element_size)
    followed by zlib-compressed payload data.

    Parameters
    ----------
    values : np.ndarray
        1-D array of values to encode.
    is_double : bool
        If True (default), encode as 8-byte doubles (float64).
        If False, encode as 4-byte floats (float32).

    Returns
    -------
    bytes
        The encoded BLOB ready to write into a SQLite BLOB column.
    """
    if values is None or len(values) == 0:
        elem_size = 8 if is_double else 4
        header = struct.pack("<4I", 16, 0, 0, elem_size)
        return header

    arr = np.asarray(values, dtype=("<f8" if is_double else "<f4"))
    raw_payload = arr.tobytes()
    compressed = zlib.compress(raw_payload, level=6)

    elem_size = 8 if is_double else 4
    count = len(arr)
    blob_size = 16 + len(compressed)
    uncomp_size = len(raw_payload)

    header = struct.pack("<4I", blob_size, uncomp_size, count, elem_size)
    return header + compressed


def encode_raw_blob_doubles(values: np.ndarray) -> bytes:
    """
    Encode a NumPy array into a raw (non-compressed) BLOB with 16-byte header.

    This is the inverse of :func:`decode_raw_blob_doubles`.
    """
    arr = np.asarray(values, dtype="<f8")
    raw_payload = arr.tobytes()
    count = len(arr)
    elem_size = 8
    blob_size = 16 + len(raw_payload)
    header = struct.pack("<4I", blob_size, len(raw_payload), count, elem_size)
    return header + raw_payload


